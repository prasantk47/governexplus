class LinkBackingControlRequest(BaseModel):
    process_control_id: str = Field(
        ...,
        description="The control_id (business key) of the ProcessControl in the PC module",
    )


@router.get("/controls/{control_id}/backing-status")
def get_backing_status(
    control_id: str,
    db: Session = Depends(get_db),
    tenant_id: str = Depends(_get_tenant_id),
) -> Dict[str, Any]:
    """
    XL-C — Backing control status for a mitigation.

    Looks up the MitigationControl whose control_id matches *control_id*,
    then follows its process_control_id foreign key into the PC module to
    retrieve:
      - The latest ControlTest result and date
      - Count of open ControlDeficiency records (open + in_remediation)
      - The backing ProcessControl name, status, and key_control flag

    If no process_control_id is set on the mitigation, the response
    indicates the control is unlinked.
    """
    from db.models.risk import MitigationControl
    from db.models.process_control import (
        ProcessControl, ControlTest, ControlDeficiency,
        DeficiencyStatus, TestResult,
    )

    mitigation = db.query(MitigationControl).filter(
        MitigationControl.tenant_id == tenant_id,
        MitigationControl.control_id == control_id,
        MitigationControl.is_active == True,  # noqa: E712
    ).first()

    if not mitigation:
        raise HTTPException(
            status_code=404,
            detail=f"Mitigation control '{control_id}' not found",
        )

    base = mitigation.to_dict()

    if not mitigation.process_control_id:
        return {
            **base,
            "backing_control_linked": False,
            "backing_control": None,
            "latest_test_result": None,
            "latest_test_date": None,
            "open_deficiency_count": 0,
            "material_weakness_count": 0,
        }

    pc = db.query(ProcessControl).filter(
        ProcessControl.tenant_id == tenant_id,
        ProcessControl.control_id == mitigation.process_control_id,
        ProcessControl.is_active == True,  # noqa: E712
    ).first()

    if not pc:
        return {
            **base,
            "backing_control_linked": True,
            "backing_control": None,
            "backing_control_missing": True,
            "latest_test_result": None,
            "latest_test_date": None,
            "open_deficiency_count": 0,
            "material_weakness_count": 0,
        }

    # Latest test result
    latest_test = (
        db.query(ControlTest)
        .filter(
            ControlTest.tenant_id == tenant_id,
            ControlTest.control_id == pc.id,
        )
        .order_by(ControlTest.created_at.desc())
        .first()
    )

    # Open deficiency counts
    open_defs = db.query(ControlDeficiency).filter(
        ControlDeficiency.tenant_id == tenant_id,
        ControlDeficiency.control_id == pc.id,
        ControlDeficiency.status.in_([
            DeficiencyStatus.OPEN,
            DeficiencyStatus.IN_REMEDIATION,
        ]),
    ).all()

    from db.models.process_control import DeficiencySeverity
    material_weakness_count = sum(
        1 for d in open_defs if d.severity == DeficiencySeverity.MATERIAL_WEAKNESS
    )

    return {
        **base,
        "backing_control_linked": True,
        "backing_control": {
            "control_id": pc.control_id,
            "name": pc.name,
            "status": pc.status.value if pc.status else None,
            "key_control": pc.key_control,
            "frequency": pc.frequency.value if pc.frequency else None,
            "owner_name": pc.owner_name,
        },
        "latest_test_result": latest_test.result.value if latest_test and latest_test.result else None,
        "latest_test_date": latest_test.created_at.isoformat() if latest_test and latest_test.created_at else None,
        "open_deficiency_count": len(open_defs),
        "material_weakness_count": material_weakness_count,
    }


@router.get("/unlinked-report")
def get_unlinked_report(
    db: Session = Depends(get_db),
    tenant_id: str = Depends(_get_tenant_id),
) -> Dict[str, Any]:
    """
    XL-C — Unified Register Gap Report (sales-demo query).

    Returns all active mitigation controls that fall into one of two gap
    categories, demonstrating the value of a unified AC+PC register:

    1. **Unlinked** — no process_control_id is set; the mitigation has no
       backing internal control and therefore receives no testing, sign-off,
       or framework coverage from the PC module.

    2. **Ineffective backing** — a process_control_id is set, but the linked
       ProcessControl's most recent ControlTest result is 'ineffective'; the
       mitigation's asserted coverage is contradicted by audit evidence.

    Each result includes:
      gap_reason   : 'no_backing_control' | 'ineffective_backing_test'
      control_id   : MitigationControl business key
      control_name : human-readable name
      process_control_id : the PC control ID (None when unlinked)
      latest_test_result : the PC test result (None when unlinked)
      latest_test_date   : ISO timestamp of the last test
    """
    from db.models.risk import MitigationControl
    from db.models.process_control import ProcessControl, ControlTest, TestResult

    mitigations = db.query(MitigationControl).filter(
        MitigationControl.tenant_id == tenant_id,
        MitigationControl.is_active == True,  # noqa: E712
    ).all()

    gaps: List[Dict[str, Any]] = []

    for m in mitigations:
        if not m.process_control_id:
            # Gap type 1: no backing control at all
            gaps.append({
                "gap_reason": "no_backing_control",
                "control_id": m.control_id,
                "control_name": m.control_name,
                "control_type": m.control_type,
                "owner_name": m.owner_name,
                "process_control_id": None,
                "latest_test_result": None,
                "latest_test_date": None,
                "valid_to": m.valid_to.isoformat() if m.valid_to else None,
            })
            continue

        # Gap type 2: backing control exists — check latest test
        pc = db.query(ProcessControl).filter(
            ProcessControl.tenant_id == tenant_id,
            ProcessControl.control_id == m.process_control_id,
            ProcessControl.is_active == True,  # noqa: E712
        ).first()

        if not pc:
            # Linked control_id no longer exists in PC — treat as unlinked
            gaps.append({
                "gap_reason": "no_backing_control",
                "control_id": m.control_id,
                "control_name": m.control_name,
                "control_type": m.control_type,
                "owner_name": m.owner_name,
                "process_control_id": m.process_control_id,
                "backing_control_missing": True,
                "latest_test_result": None,
                "latest_test_date": None,
                "valid_to": m.valid_to.isoformat() if m.valid_to else None,
            })
            continue

        latest_test = (
            db.query(ControlTest)
            .filter(
                ControlTest.tenant_id == tenant_id,
                ControlTest.control_id == pc.id,
            )
            .order_by(ControlTest.created_at.desc())
            .first()
        )

        if latest_test and latest_test.result == TestResult.INEFFECTIVE:
            gaps.append({
                "gap_reason": "ineffective_backing_test",
                "control_id": m.control_id,
                "control_name": m.control_name,
                "control_type": m.control_type,
                "owner_name": m.owner_name,
                "process_control_id": m.process_control_id,
                "backing_control_name": pc.name,
                "latest_test_result": latest_test.result.value,
                "latest_test_date": latest_test.created_at.isoformat() if latest_test.created_at else None,
                "valid_to": m.valid_to.isoformat() if m.valid_to else None,
            })

    no_backing = sum(1 for g in gaps if g["gap_reason"] == "no_backing_control")
    ineffective = sum(1 for g in gaps if g["gap_reason"] == "ineffective_backing_test")

    return {
        "generated_at": __import__("datetime").datetime.utcnow().isoformat(),
        "total_active_mitigations": len(mitigations),
        "total_gaps": len(gaps),
        "summary": {
            "no_backing_control": no_backing,
            "ineffective_backing_test": ineffective,
        },
        "gaps": gaps,
    }


@router.put("/controls/{control_id}/link")
def link_backing_control(
    control_id: str,
    body: LinkBackingControlRequest,
    db: Session = Depends(get_db),
    tenant_id: str = Depends(_get_tenant_id),
) -> Dict[str, Any]:
    """
    XL-C — Link a MitigationControl to its backing ProcessControl.

    Sets process_control_id on the MitigationControl identified by *control_id*.
    The backing control is validated to exist and be active in this tenant.

    After linking, call GET /controls/{control_id}/backing-status to see the
    full PC test and deficiency picture for this mitigation.
    """
    from db.models.risk import MitigationControl
    from db.models.process_control import ProcessControl

    mitigation = db.query(MitigationControl).filter(
        MitigationControl.tenant_id == tenant_id,
        MitigationControl.control_id == control_id,
        MitigationControl.is_active == True,  # noqa: E712
    ).first()

    if not mitigation:
        raise HTTPException(
            status_code=404,
            detail=f"Mitigation control '{control_id}' not found",
        )

    # Validate that the target ProcessControl exists in this tenant
    pc = db.query(ProcessControl).filter(
        ProcessControl.tenant_id == tenant_id,
        ProcessControl.control_id == body.process_control_id,
        ProcessControl.is_active == True,  # noqa: E712
    ).first()

    if not pc:
        raise HTTPException(
            status_code=404,
            detail=(
                f"ProcessControl '{body.process_control_id}' not found or inactive "
                f"for this tenant. Create it in the Process Control module first."
            ),
        )

    previous_id = mitigation.process_control_id
    mitigation.process_control_id = body.process_control_id
    db.commit()

    logger.info(
        "xlc.link_backing_control",
        mitigation_id=control_id,
        process_control_id=body.process_control_id,
        previous_id=previous_id,
        tenant_id=tenant_id,
    )

    return {
        "control_id": control_id,
        "process_control_id": body.process_control_id,
        "backing_control_name": pc.name,
        "previously_linked_to": previous_id,
        "linked_at": __import__("datetime").datetime.utcnow().isoformat(),
        "message": (
            f"Mitigation '{control_id}' is now backed by ProcessControl "
            f"'{body.process_control_id}' ({pc.name}). "
            "Call GET /controls/{control_id}/backing-status for full coverage details."
        ),
    }
