"""
Mitigation Monitoring API Router

Endpoints for checking mitigation health, viewing expiring/expired controls,
triggering full health checks, and managing scheduled monitoring jobs.

XL-C additions (Unified Mitigation Register — Loop C):
  GET  /controls/{control_id}/backing-status  — backing PC control test + deficiency status
  GET  /unlinked-report                       — mitigations with no tested backing control
  PUT  /controls/{control_id}/link            — attach a process_control_id to a mitigation
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional

from fastapi import APIRouter, Depends, HTTPException, Query
from pydantic import BaseModel, Field
from sqlalchemy.orm import Session

from core.mitigation.monitoring import get_monitor
from core.logging import get_logger
from db.database import get_db

logger = get_logger(__name__)
router = APIRouter(tags=["Mitigation Monitoring"])
_monitor = get_monitor()


# ---------------------------------------------------------------------------
# Tenant helper
# ---------------------------------------------------------------------------

def _get_tenant_id() -> str:
    from core.tenant import get_current_tenant
    ctx = get_current_tenant()
    return ctx.tenant_id if ctx else "default"


# ---------------------------------------------------------------------------
# Request models
# ---------------------------------------------------------------------------

class RunCheckRequest(BaseModel):
    days_ahead: int = Field(
        default=30,
        ge=1,
        le=180,
        description="Days of lookahead for expiry detection",
    )


class ScheduleRequest(BaseModel):
    interval_hours: int = Field(
        default=24,
        ge=1,
        le=168,
        description="How often (in hours) to run the full check. Max 168 (7 days).",
    )


# ---------------------------------------------------------------------------
# Endpoints
# ---------------------------------------------------------------------------

@router.get("/health")
async def get_health_dashboard() -> Dict[str, Any]:
    """
    Return the mitigation health dashboard.

    Provides a high-level overview: health score, counts of expiring /
    expired / ineffective controls, unassigned violations, and recent alerts.
    No new alerts are generated by this endpoint.
    """
    return _monitor.get_health_dashboard()


@router.get("/expiring")
async def get_expiring_mitigations(
    days_ahead: int = Query(
        default=30,
        ge=1,
        le=180,
        description="Days ahead to include in the expiry window",
    ),
) -> Dict[str, Any]:
    """
    List mitigation controls expiring within the specified number of days.

    Returns each control with a 'days_remaining' field.
    Results are ordered by days remaining (soonest first).
    """
    controls = _monitor.check_expiring_mitigations(days_ahead=days_ahead)
    controls.sort(key=lambda c: c.get("days_remaining") or 9999)
    return {
        "days_ahead": days_ahead,
        "total": len(controls),
        "controls": controls,
    }


@router.get("/expired")
async def get_expired_mitigations() -> Dict[str, Any]:
    """
    List all mitigation controls that have already expired.

    Returns each control with a 'days_overdue' field indicating how many
    days ago the control expired.
    """
    controls = _monitor.check_expired_mitigations()
    controls.sort(key=lambda c: c.get("days_overdue") or 0, reverse=True)
    return {
        "total": len(controls),
        "controls": controls,
    }


@router.get("/unassigned")
async def get_unassigned_violations() -> Dict[str, Any]:
    """
    List SoD/risk violations that have no mitigation control assigned.

    Results are ordered by risk severity (critical first).
    These violations represent unacceptable open risks.
    """
    violations = _monitor.check_unassigned_violations()
    return {
        "total": len(violations),
        "violations": violations,
    }


@router.get("/ineffective")
async def get_ineffective_controls() -> Dict[str, Any]:
    """
    List active controls whose effectiveness score is below the threshold (50%).

    Returns each control with an 'effectiveness_gap' showing how far below the
    threshold the score is.
    """
    controls = _monitor.check_control_effectiveness()
    return {
        "total": len(controls),
        "threshold": _monitor.INEFFECTIVE_THRESHOLD,
        "controls": controls,
    }


@router.post("/run-check")
async def run_full_check(req: RunCheckRequest) -> Dict[str, Any]:
    """
    Execute a full mitigation health check immediately.

    Runs all four checks (expiring, expired, unassigned, ineffective),
    generates alerts, and returns a complete MitigationHealthReport.
    """
    report = _monitor.run_full_check(days_ahead=req.days_ahead)
    logger.info(
        "api.full_check_run",
        alerts_generated=report.alerts_generated,
        days_ahead=req.days_ahead,
    )
    return report.to_dict()


@router.get("/alerts")
async def get_alerts(
    alert_type: Optional[str] = Query(
        None,
        description="Filter by type: expiring, expired, unassigned_violation, ineffective_control",
    ),
    severity: Optional[str] = Query(
        None,
        description="Filter by severity: info, warning, critical",
    ),
    limit: int = Query(default=100, ge=1, le=500),
) -> Dict[str, Any]:
    """
    Return the history of alerts generated by past monitoring runs.

    Supports optional filtering by alert type and severity.
    Returns most recent alerts first.
    """
    # Validate optional enum values
    valid_types = {"expiring", "expired", "unassigned_violation", "ineffective_control"}
    valid_severities = {"info", "warning", "critical"}

    if alert_type and alert_type not in valid_types:
        raise HTTPException(
            status_code=422,
            detail=f"Invalid alert_type '{alert_type}'. Valid: {sorted(valid_types)}",
        )
    if severity and severity not in valid_severities:
        raise HTTPException(
            status_code=422,
            detail=f"Invalid severity '{severity}'. Valid: {sorted(valid_severities)}",
        )

    alerts = _monitor.get_alert_history(
        alert_type=alert_type,
        severity=severity,
        limit=limit,
    )
    return {
        "total": len(alerts),
        "filters": {"alert_type": alert_type, "severity": severity},
        "alerts": alerts,
    }


@router.post("/schedule")
async def schedule_check(req: ScheduleRequest) -> Dict[str, Any]:
    """
    Start (or restart) the background monitoring scheduler.

    The scheduler runs run_full_check() at the specified interval.
    Calling this endpoint while a scheduler is already running will
    stop the previous one and start a new one with the new interval.
    """
    result = _monitor.schedule_check(interval_hours=req.interval_hours)
    logger.info("api.scheduler_started", interval_hours=req.interval_hours)
    return {
        "message": "Mitigation monitoring scheduler started",
        **result,
    }


